// Generates THIRD_PARTY_NOTICES.md by walking the production dependency tree
// and reproducing each package's license text. Run after `npm install`:
//
//   node scripts/gen-third-party-notices.mjs
//
// Why this exists: MIT / BSD / ISC / Apache-2.0 (and the rest of the tree) all
// require the copyright notice + license text to travel with any distribution,
// including the signed desktop binaries shipped via morion-releases. This file
// is the bundled attribution. Re-run it whenever production dependencies change.

import { execSync } from 'node:child_process'
import { readFileSync, existsSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = process.cwd()
const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = join(ROOT, 'THIRD_PARTY_NOTICES.md')

// Canonical full texts for copyleft/strong licenses whose npm tarballs do not
// bundle a LICENSE file. LGPL-3.0 incorporates GPL-3.0 by reference, so both
// are reproduced. Sourced verbatim from gnu.org. Keyed by SPDX id.
function canonicalText(spdx) {
  const file = (() => {
    if (/LGPL-3\.0/i.test(spdx)) return 'LGPL-3.0.txt'
    if (/(^|[^L])GPL-3\.0/i.test(spdx)) return 'GPL-3.0.txt'
    if (/Apache-2\.0/i.test(spdx)) return 'Apache-2.0.txt'
    return null
  })()
  if (!file) return null
  const p = join(HERE, 'license-texts', file)
  if (!existsSync(p)) return null
  let txt = readFileSync(p, 'utf8').trim()
  // LGPL-3.0 references GPL-3.0; append the GPL text so the notice is complete.
  if (file === 'LGPL-3.0.txt') {
    const gpl = join(HERE, 'license-texts', 'GPL-3.0.txt')
    if (existsSync(gpl)) {
      txt += '\n\n' + '='.repeat(70) + '\n' +
        'The GNU General Public License v3.0, referenced above:\n' +
        '='.repeat(70) + '\n\n' + readFileSync(gpl, 'utf8').trim()
    }
  }
  return txt
}

const LICENSE_FILE_RE = /^(LICENSE|LICENCE|COPYING|NOTICE)(\..*)?$/i

function readJson(p) {
  try {
    return JSON.parse(readFileSync(p, 'utf8'))
  } catch {
    return null
  }
}

function licenseText(dir) {
  let entries
  try {
    entries = readdirSync(dir)
  } catch {
    return null
  }
  const files = entries.filter((f) => LICENSE_FILE_RE.test(f))
  // Prefer the plain LICENSE/LICENCE file over NOTICE when both exist.
  files.sort((a, b) => {
    const an = /^notice/i.test(a) ? 1 : 0
    const bn = /^notice/i.test(b) ? 1 : 0
    return an - bn
  })
  for (const f of files) {
    try {
      const txt = readFileSync(join(dir, f), 'utf8').trim()
      if (txt) return txt
    } catch {
      /* keep looking */
    }
  }
  return null
}

function spdx(pkg) {
  if (typeof pkg.license === 'string') return pkg.license
  if (pkg.license && pkg.license.type) return pkg.license.type
  if (Array.isArray(pkg.licenses) && pkg.licenses[0]) return pkg.licenses[0].type || 'UNKNOWN'
  return 'UNKNOWN'
}

function homepage(pkg) {
  if (pkg.homepage) return pkg.homepage
  const r = pkg.repository
  if (typeof r === 'string') return r
  if (r && r.url) return r.url.replace(/^git\+/, '').replace(/\.git$/, '')
  return null
}

// `npm ls` exits non-zero on peer-dependency warnings (ELSPROBLEMS) but still
// prints the full tree to stdout, so capture stdout regardless of exit code.
function npmLsDirs() {
  try {
    return execSync('npm ls --omit=dev --all --parseable', { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
  } catch (e) {
    if (e.stdout) return e.stdout.toString()
    throw e
  }
}

const dirs = npmLsDirs()
  .split('\n')
  .map((s) => s.trim())
  .filter(Boolean)
  .filter((d) => d !== ROOT)

const seen = new Map()
for (const dir of dirs) {
  const pkgPath = join(dir, 'package.json')
  if (!existsSync(pkgPath)) continue
  const pkg = readJson(pkgPath)
  if (!pkg || !pkg.name) continue
  const key = `${pkg.name}@${pkg.version}`
  if (seen.has(key)) continue
  const license = spdx(pkg)
  seen.set(key, {
    name: pkg.name,
    version: pkg.version,
    license,
    homepage: homepage(pkg),
    text: licenseText(dir) || canonicalText(license),
  })
}

const pkgs = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))

const counts = {}
for (const p of pkgs) counts[p.license] = (counts[p.license] || 0) + 1
const summary = Object.entries(counts).sort((a, b) => b[1] - a[1])

const lines = []
lines.push('# Third-Party Notices')
lines.push('')
lines.push('Morion is distributed with the open-source packages listed below. Each is')
lines.push('the property of its respective authors and is provided under its own license.')
lines.push('Their copyright notices and license texts are reproduced here as required by')
lines.push('those licenses. This file is generated by `scripts/gen-third-party-notices.mjs`')
lines.push('from the production dependency tree — do not edit it by hand.')
lines.push('')
lines.push(`Total packages: ${pkgs.length}`)
lines.push('')
lines.push('## License summary')
lines.push('')
lines.push('| License | Packages |')
lines.push('| --- | --- |')
for (const [lic, n] of summary) lines.push(`| ${lic} | ${n} |`)
lines.push('')
lines.push('## Note on libvips (LGPL-3.0)')
lines.push('')
lines.push('`@img/sharp-libvips-*` is licensed under LGPL-3.0-or-later and ships as a')
lines.push('separate, prebuilt shared library that `sharp` loads dynamically at runtime')
lines.push('(it is not statically linked into Morion source code). It reaches Morion')
lines.push('transitively via `@huggingface/transformers` -> `sharp`. In accordance with')
lines.push('the LGPL, the library is distributed as an independent, replaceable component:')
lines.push('users may substitute their own build of libvips. The full LGPL-3.0 text is')
lines.push('reproduced with the package entry below.')
lines.push('')
lines.push('---')
lines.push('')
lines.push('## Packages')
lines.push('')

for (const p of pkgs) {
  lines.push(`### ${p.name}@${p.version}`)
  lines.push('')
  lines.push(`- License: ${p.license}`)
  if (p.homepage) lines.push(`- Homepage: ${p.homepage}`)
  lines.push('')
  if (p.text) {
    lines.push('```')
    lines.push(p.text)
    lines.push('```')
  } else {
    lines.push(`_No license file bundled with this package; declared license: ${p.license}._`)
  }
  lines.push('')
}

writeFileSync(OUT, lines.join('\n') + '\n')
console.log(`Wrote ${OUT} — ${pkgs.length} packages.`)
